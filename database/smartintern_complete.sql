-- PART 19: FUNCTION
-- Count applications for a particular job
-- ============================================================

CREATE OR REPLACE FUNCTION get_application_count(
    p_job_id BIGINT
)
RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
    total_count INTEGER;
BEGIN
    SELECT COUNT(*)::INTEGER
    INTO total_count
    FROM applications
    WHERE job_id = p_job_id;

    RETURN total_count;
END;
$$;


