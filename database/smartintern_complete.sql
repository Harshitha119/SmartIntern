CREATE OR REPLACE VIEW application_summary_view AS
SELECT
    a.application_id,
    u.full_name,
    u.email,
    j.title AS job_title,
    a.status,
    a.applied_at
FROM applications a
JOIN users u ON a.user_id = u.user_id
JOIN jobs j ON a.job_id = j.job_id;


