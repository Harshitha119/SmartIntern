-- 1. Applications with student and job details

SELECT
    u.full_name,
    j.title AS job_title,
    a.status,
    a.applied_at
FROM applications a
JOIN users u ON a.user_id = u.user_id
JOIN jobs j ON a.job_id = j.job_id
ORDER BY a.applied_at DESC;


-- 2. Jobs with company names

SELECT
    j.job_id,
    j.title,
    c.company_name,
    j.location,
    j.opportunity_type
FROM jobs j
JOIN companies c ON j.company_id = c.company_id;


-- 3. Student skills

SELECT
    u.full_name,
    s.skill_name,
    ss.proficiency
FROM student_skills ss
JOIN users u ON ss.user_id = u.user_id
JOIN skills s ON ss.skill_id = s.skill_id;


-- 4. Job skills

SELECT
    j.title,
    s.skill_name,
    js.importance
FROM job_skills js
JOIN jobs j ON js.job_id = j.job_id
JOIN skills s ON js.skill_id = s.skill_id;


-- ============================================================
-- PART 11: GROUP BY, COUNT AND HAVING
-- ============================================================

-- 1. Number of applications per job

SELECT
    j.title,
    COUNT(a.application_id) AS total_applications
FROM jobs j
LEFT JOIN applications a ON j.job_id = a.job_id
GROUP BY j.job_id, j.title
ORDER BY total_applications DESC;


-- 2. Jobs receiving more than two applications

SELECT
    j.title,
    COUNT(a.application_id) AS total_applications
FROM jobs j
JOIN applications a ON j.job_id = a.job_id
GROUP BY j.job_id, j.title
HAVING COUNT(a.application_id) > 2;


