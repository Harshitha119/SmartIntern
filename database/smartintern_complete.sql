CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    role VARCHAR(30) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS student_profiles (
    profile_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT UNIQUE REFERENCES users(user_id),
    degree VARCHAR(100),
    branch VARCHAR(100),
    university VARCHAR(150),
    graduation_year INTEGER,
    cgpa NUMERIC(4,2),
    experience_years NUMERIC(5,2)
);

CREATE TABLE IF NOT EXISTS resumes (
    resume_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(user_id),
    file_name VARCHAR(255),
    file_path TEXT,
    extracted_text TEXT,
    uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS skills (
    skill_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_name VARCHAR(100) UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS student_skills (
    user_id BIGINT REFERENCES users(user_id),
    skill_id BIGINT REFERENCES skills(skill_id),
    proficiency VARCHAR(50),
    PRIMARY KEY (user_id, skill_id)
);

CREATE TABLE IF NOT EXISTS companies (
    company_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name VARCHAR(150) NOT NULL,
    industry VARCHAR(100),
    website TEXT,
    description TEXT
);

CREATE TABLE IF NOT EXISTS jobs (
    job_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT REFERENCES companies(company_id),
    title VARCHAR(200) NOT NULL,
    description TEXT,
    opportunity_type VARCHAR(100),
    location VARCHAR(150),
    min_cgpa NUMERIC(4,2),
    stipend_or_salary VARCHAR(150),
    application_deadline DATE,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS job_skills (
    job_id BIGINT REFERENCES jobs(job_id),
    skill_id BIGINT REFERENCES skills(skill_id),
    importance VARCHAR(50),
    PRIMARY KEY (job_id, skill_id)
);

CREATE TABLE IF NOT EXISTS applications (
    application_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(user_id),
    job_id BIGINT REFERENCES jobs(job_id),
    status VARCHAR(50),
    applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS recommendation_runs (
    recommendation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(user_id),
    job_id BIGINT REFERENCES jobs(job_id),
    match_percentage NUMERIC(5,2),
    matching_skills TEXT,
    missing_skills TEXT,
    explanation TEXT,
    generated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS inbox_messages (
    message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id BIGINT REFERENCES users(user_id),
    recipient_id BIGINT REFERENCES users(user_id),
    subject VARCHAR(255),
    body TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMP
);


