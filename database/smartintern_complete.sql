-- ============================================================
-- PART 20: TRIGGER
-- Automatically set application date
-- ============================================================

CREATE OR REPLACE FUNCTION set_application_date()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.applied_at IS NULL THEN
        NEW.applied_at := CURRENT_TIMESTAMP;
    END IF;

    RETURN NEW;
END;
$$;


DROP TRIGGER IF EXISTS trg_application_date
ON applications;


CREATE TRIGGER trg_application_date
BEFORE INSERT ON applications
FOR EACH ROW
EXECUTE FUNCTION set_application_date();


-- ============================================================
-- PART 21: STORED PROCEDURE
-- Update application status
-- ============================================================

CREATE OR REPLACE PROCEDURE update_application_status(
    p_application_id BIGINT,
    p_new_status VARCHAR(50)
)
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE applications
    SET status = p_new_status
    WHERE application_id = p_application_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Application not found';
    END IF;
END;
$$;


